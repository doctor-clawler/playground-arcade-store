import fs from "node:fs";
import path from "node:path";

const dictionaryPath = path.resolve("node_modules/dictionary-ko/index.dic");
const outputPath = path.resolve("src/generatedDictionary.js");
const raw = fs.readFileSync(dictionaryPath, "utf8");
const words = new Set();
const hangulOnly = /^[가-힣]+$/u;

for (const line of raw.split(/\r?\n/).slice(1)) {
  const word = line.split("/")[0]?.trim().normalize("NFC");
  if (!word || word.length > 8 || !hangulOnly.test(word)) {
    continue;
  }
  words.add(word);
}

const sortedWords = [...words].sort((left, right) => left.localeCompare(right, "ko"));
const contents = [
  "// Generated by scripts/build-dictionary.mjs from dictionary-ko/index.dic.",
  "// Do not edit by hand.",
  `export const GENERATED_KOREAN_WORDS = Object.freeze(${JSON.stringify(sortedWords)});`,
  "",
].join("\n");

fs.writeFileSync(outputPath, contents);
console.log(`generated ${sortedWords.length} Korean words at ${outputPath}`);
